import { _electron as electron } from 'playwright';
const ud = process.argv[2];
const app = await electron.launch({ args: ['.'], env: { ...process.env, DROPEXE_USERDATA: ud } });
app.process().stdout.on('data', (d) => process.stdout.write('[main] ' + d));
app.process().stderr.on('data', (d) => process.stdout.write('[main!] ' + d));
const w = await app.firstWindow();
w.on('console', (m) => { if (!/Security/.test(m.text())) console.log('[page]', m.text()); });
w.on('pageerror', (e) => console.log('[pageerror]', e.message));
const t0 = Date.now();
await w.waitForTimeout(1500);
await w.click('.tab[data-tab="stores"]');
const r = w.evaluate(() => window.dx.addStore('steam'));
let last = '';
const iv = setInterval(async () => { try { const j = await w.textContent('.job-text'); if (j !== last) { last = j; console.log(((Date.now() - t0) / 1000) | 0, 's', j); } } catch {} }, 1000);
console.log('result', JSON.stringify(await r));
clearInterval(iv);
await w.waitForTimeout(45000);
console.log(JSON.stringify((await w.evaluate(() => window.dx.state())).items.map((i) => [i.id, i.running])));
await w.click('.tab[data-tab="library"]'); await w.waitForTimeout(800);
await w.screenshot({ path: `${ud}/steam-running.png` });
await w.evaluate(() => window.dx.stop('store-steam'));
await app.close();
